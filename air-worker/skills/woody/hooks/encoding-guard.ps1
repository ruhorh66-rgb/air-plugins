<#
.SYNOPSIS
  Страж кодировки: правило о BOM исполняется в момент записи файла, а не вспоминается.

.DESCRIPTION
  Указание ЛПР 13.09.2026: «ты постоянно ссылаешься на BOM, что у нас ошибки — давай
  зашивать это в хуки».

  Основание прямое и измеренное: за одни сутки эта беда стоила ЧЕТЫРЁХ отказов, и каждый
  раз правило записывалось словами — в комментарий, в память, в журнал изменений, — и
  каждый раз не срабатывало в следующем месте. Правило, живущее уроком, чинится там, где
  найдено, и уцелевает дальше. Единственный способ его прекратить — исполнять механизмом.

  ПОЧЕМУ ИМЕННО ХУК, А НЕ ПРОВЕРКА СУДЬИ. Судья зовётся раз в прогон и говорит о продукте
  целиком; к тому времени файл уже написан, закоммичен и, возможно, отправлен соседу.
  Хук срабатывает НА ЗАПИСИ — то есть там, где ошибка возникает, и до того, как она
  успевает во что-нибудь превратиться.

  ПОЧЕМУ ЧИНИТ, А НЕ ОТКАЗЫВАЕТ. Событие приходит ПОСЛЕ записи: отказывать поздно, файл
  уже на диске. Выбор между «оставить сломанным и пожаловаться» и «исправить и сказать»
  решается тем, что правило детерминировано и узко: у .ps1 BOM обязан быть, у .md, .json
  и .go его быть не должно. Здесь нечего решать человеку, а значит нечего и спрашивать.

  ЧУЖИЕ ТИПЫ НЕ ТРОГАЮТСЯ ВОВСЕ. Правило известно для перечисленных расширений; для
  остальных хук молчит. Молча «починить» незнакомый формат хуже, чем не тронуть.

  ПРАВИЛО ЖИВЁТ В БИНАРНИКЕ, а здесь только доставка события до него. Второй реализации
  того же правила в PowerShell не заводится: две реализации одного правила расходятся
  молча — это единственный урок, который за сегодня подтвердился семь раз.

  Хук ПРОПУСКАЕТ при любой своей ошибке. Сторож, ломающий работу, когда сломался сам,
  снимут первым же движением и вместе с пользой.
#>
[CmdletBinding()]
param()

$ErrorActionPreference = 'Continue'

try {
    $raw = [Console]::In.ReadToEnd()
    if (-not $raw) { exit 0 }
    $ev = $raw | ConvertFrom-Json

    # Путь берётся из входа инструмента. Имена полей разнятся между инструментами записи,
    # поэтому берутся все известные, а не одно: неизвестное имя даст молчание, а молчание
    # здесь неотличимо от исправности.
    $paths = @()
    foreach ($n in @('file_path', 'filePath', 'path', 'notebook_path')) {
        $v = $ev.tool_input.$n
        if ($v) { $paths += [string]$v }
    }
    if ($paths.Count -eq 0) { exit 0 }

    # Бинарник продукта — единственный носитель правила. Ищется по ответу, а не по
    # прибитому пути: перекрытие, затем каталог плагина, затем известное расположение.
    $exe = $env:AIR_WORKER_EXE
    if (-not $exe -and $env:CLAUDE_PLUGIN_ROOT) {
        $exe = Join-Path $env:CLAUDE_PLUGIN_ROOT 'bin\air-worker.exe'
    }
    if (-not $exe -or -not (Test-Path -LiteralPath $exe)) {
        # От hooks до корня продукта ТРИ уровня: hooks -> woody -> skills -> корень.
        # Первая редакция поднималась на два и молча искала bin в каталоге skills:
        # страж не находил бинарника и не делал ничего, ничем об этом не сообщая.
        $root = Split-Path -Parent (Split-Path -Parent (Split-Path -Parent $PSScriptRoot))
        $exe = Join-Path $root 'bin\air-worker.exe'
    }
    if (-not (Test-Path -LiteralPath $exe)) { exit 0 }

    foreach ($p in $paths) {
        if (-not (Test-Path -LiteralPath $p -PathType Leaf)) { continue }
        $out = & $exe encoding -path $p -fix 2>&1 | Out-String
        $out = $out.Trim()
        # Говорит только когда ЧТО-ТО СДЕЛАЛ. Хук, печатающий «всё хорошо» на каждой
        # записи, читать перестают через час, и тогда он перестаёт работать по-настоящему.
        if ($out -like 'исправлено:*') {
            [Console]::Error.WriteLine("СТРАЖ КОДИРОВКИ: $out")
        }
    }
}
catch { }

exit 0
