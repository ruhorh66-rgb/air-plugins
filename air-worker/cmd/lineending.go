package main

import "runtime"

// lineEnding — окончание строки то же, что у PowerShell на этой платформе.
//
// Пока две реализации живут рядом, побайтовое расхождение вывода означает ложное
// «изменилось» для всякого, кто сравнивает вердикты хешем или diff. Разница в один байт
// не видна глазом и потому опаснее крупной.
var lineEnding = func() string {
	if runtime.GOOS == "windows" {
		return "\r\n"
	}
	return "\n"
}()